const resources = {
  en: { translation: en },
  es: { translation: es },
} as const;

void i18n
  .use(initReactI18next)
  .init({
    resources,
    lng: resolveLocale(readLocalePreference()),
    fallbackLng: "en",
    supportedLngs: ["en", "es"],
    interpolation: { escapeValue: false },
    initImmediate: false,
    returnNull: false,
  });

document.documentElement.lang = resolveLocale(readLocalePreference());

window.addEventListener("languagechange", () => {
  if (readLocalePreference() === "system") {
    void applyLocalePreference("system");
  }
});

export default i18n;

export function readLocalePreference(): LocalePreference {
  const value = window.localStorage.getItem(LOCALE_STORAGE_KEY);
  return value === "en" || value === "es" || value === "system"
    ? value
    : "system";
}

export function resolveLocale(
  preference: LocalePreference,
): SupportedLocale {
  if (preference === "en" || preference === "es") return preference;

  const languages =
    navigator.languages?.length > 0
      ? navigator.languages
      : [navigator.language];
  return languages.some((language) =>
    language.toLocaleLowerCase().startsWith("es"),
  )
    ? "es"
    : "en";
}

export async function applyLocalePreference(
  preference: LocalePreference,
): Promise<void> {
  window.localStorage.setItem(LOCALE_STORAGE_KEY, preference);
  const locale = resolveLocale(preference);
  document.documentElement.lang = locale;
  if (i18n.resolvedLanguage !== locale) {
    await i18n.changeLanguage(locale);
  }
}
